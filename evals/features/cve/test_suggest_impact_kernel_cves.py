# Without the kernel classifier the LLM alone underestimates these
# IMPORTANT-severity kernel CVEs to MODERATE.  The classifier provides
# the additional signal needed to reach the correct impact band.
if not get_settings().use_kernel_classifier:
    _NO_CLF_WAIVER: dict = {
        "known_to_fail_evaluators": ["UnderestimationEvaluator"],
        "reason": (
            "LLM-only underestimation (MODERATE vs IMPORTANT) — "
            "requires kernel classifier to reach correct impact."
        ),
    }
    for _cve in ("CVE-2025-38590", "CVE-2023-53186", "CVE-2026-23074"):
        KNOWN_FAILURES[_cve] = _NO_CLF_WAIVER


def _normalize_impact(raw: str) -> str:
    """'Important' -> 'IMPORTANT', 'Moderate <= 5.5' -> 'MODERATE'"""
    parts = raw.strip().split()
    return parts[0].upper() if parts else ""


class UnderestimationEvaluator(Evaluator[str, SuggestImpactModel]):
    """Fail when the predicted impact is strictly lower than expected.

    Underestimation means a high-impact vulnerability ships without the
    urgency it deserves.  Overestimation merely triggers extra review.
    """

    def evaluate(
        self, ctx: EvaluatorContext[str, SuggestImpactModel]
    ) -> EvaluationReason:
        assert ctx.expected_output is not None
        actual = (ctx.output.impact or "").strip().upper()
        expected = (ctx.expected_output.impact or "").strip().upper()

        if not actual or not expected:
            return EvaluationReason(value=True)

        actual_rank = SEVERITY_RANK.get(actual, 4)
        expected_rank = SEVERITY_RANK.get(expected, 4)

        if actual_rank > expected_rank:
            return EvaluationReason(
                value=False,
                reason=f"underestimation: predicted {actual}, expected {expected}",
            )
        return EvaluationReason(value=True)


VALID_IMPACTS = {"CRITICAL", "IMPORTANT", "MODERATE", "LOW", "NONE", ""}


def _load_cases() -> list[SuggestImpactCase]:
    cases = []
    seen: set[str] = set()
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            cve_id = row["CVE"].strip()
            if not cve_id.startswith("CVE-") or cve_id in seen:
                continue
            seen.add(cve_id)

            expected_impact = _normalize_impact(row["OSIDB Impact"])
            if expected_impact not in VALID_IMPACTS:
                logger.warning(
                    "Skipping %s: invalid OSIDB impact %r",
                    cve_id,
                    row["OSIDB Impact"].strip(),
                )
                continue
            try:
                expected_cvss = float(row["OSIDB CVSS"].strip())
            except (ValueError, KeyError):
                expected_cvss = None

            expected_vector = row.get("OSIDB CVSS Vector", "").strip() or None

            metadata = KNOWN_FAILURES.get(cve_id)
            cases.append(
                SuggestImpactCase(
                    cve_id=cve_id,
                    expected_impact=expected_impact or None,
                    expected_cvss3_score=expected_cvss,
                    expected_cvss3_vector=expected_vector,
                    metadata=metadata,
                )
            )
    return cases


cases = _load_cases()

evals = common_feature_evals + [
    CVSSValidator(),
    UnderestimationEvaluator(),
]


async def suggest_impact_kernel(cve_id: CVEID) -> SuggestImpactModel:
    feature = SuggestImpact(rh_feature_agent)
    result = await feature.exec(cve_id)
    return result.output


pytestmark = pytest.mark.asyncio(loop_scope="session")


async def test_eval_suggest_impact_kernel_cves(request):
    """suggest_impact evaluation on eval-kernel-cves.csv CVEs"""
    run_audit = request.config.getoption("--audit")

    def _on_report(report, _failures):
        """Export JSON results and (optionally) audit before assertion fires."""
        export_eval_results(report, RESULTS_PATH)
        logger.info("Eval results exported to %s", RESULTS_PATH)

        if run_audit:
            from evals.features.cve.audit_kernel_eval import audit, print_report

            audit_path = RESULTS_PATH.with_name("kernel_eval_audit.json")
            audit_report = audit(RESULTS_PATH)
            print_report(audit_report)
            import json

            with open(audit_path, "w", encoding="utf-8") as f:
                json.dump(audit_report, f, indent=2)
            logger.info("Audit report written to %s", audit_path)

    await run_evaluation(
        cases,
        evals,
        suggest_impact_kernel,
        agent=rh_feature_agent,
        on_report=_on_report,
    )
