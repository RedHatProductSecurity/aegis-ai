import pytest
from pydantic import ValidationError

from aegis_ai.data_models import cveid_validator, cweid_validator
from aegis_ai.features.cve.data_models import (
    AffectedPackageEntry,
    BinaryAffectednessEntry,
    SuggestAffectedPackagesModel,
)


def test_cweid_validator():
    cwe_id = "CWE-100"
    assert cweid_validator.validate_python(cwe_id)
    with pytest.raises(ValidationError) as excinfo:
        cve_id = "BAD-CWE-4"
        assert cweid_validator.validate_python(cve_id)
    assert "String should match pattern '^CWE-[0-9]{1,5}$'" in str(excinfo)


def test_cveid_validator():
    cve_id = "CVE-2024-2004"
    assert cveid_validator.validate_python(cve_id)
    with pytest.raises(ValidationError) as excinfo:
        cve_id = "BAD-CVE-4"
        assert cveid_validator.validate_python(cve_id)
    assert "String should match pattern '^CVE-[0-9]{4}-[0-9]{4,16}$'" in str(excinfo)


DISCLAIMER = (
    "This response was generated by Aegis AI "
    "(https://github.com/RedHatProductSecurity/aegis-ai) using generative AI "
    "for informational purposes. All findings should be validated by a human expert."
)


class TestBinaryAffectednessEntry:
    def test_round_trip(self):
        entry = BinaryAffectednessEntry(
            binary_rpm="libcurl",
            affected=True,
            explanation="Contains the vulnerable HTTP/2 handler.",
        )
        data = entry.model_dump()
        restored = BinaryAffectednessEntry(**data)
        assert restored == entry
        assert restored.subcomponent_hint is None

    def test_with_subcomponent_hint(self):
        entry = BinaryAffectednessEntry(
            binary_rpm="kernel-core",
            affected=True,
            explanation="Contains the XFS module.",
            subcomponent_hint="XFS kernel module",
        )
        data = entry.model_dump()
        assert data["subcomponent_hint"] == "XFS kernel module"
        restored = BinaryAffectednessEntry(**data)
        assert restored.subcomponent_hint == "XFS kernel module"


class TestAffectedPackageEntry:
    def test_with_affected_binaries(self):
        entry = AffectedPackageEntry(
            purl="pkg:rpm/redhat/curl",
            ps_update_stream="rhel-9.6.0.z",
            affected=True,
            explanation="Package contains vulnerable code.",
            affected_binaries=[
                BinaryAffectednessEntry(
                    binary_rpm="libcurl",
                    affected=True,
                    explanation="Contains HTTP/2 handler.",
                ),
                BinaryAffectednessEntry(
                    binary_rpm="curl-minimal",
                    affected=False,
                    explanation="Minimal build excludes HTTP/2.",
                ),
            ],
        )
        data = entry.model_dump()
        restored = AffectedPackageEntry(**data)
        assert len(restored.affected_binaries) == 2
        assert restored.affected_binaries[0].binary_rpm == "libcurl"
        assert restored.affected_binaries[1].affected is False

    def test_empty_affected_binaries_by_default(self):
        entry = AffectedPackageEntry(
            purl="pkg:rpm/redhat/curl",
            ps_update_stream="rhel-9.6.0.z",
            affected=True,
            explanation="Affected.",
        )
        assert entry.affected_binaries == []

    def test_build_nvr_round_trip(self):
        entry = AffectedPackageEntry(
            purl="pkg:rpm/redhat/curl",
            ps_update_stream="rhel-9.6.0.z",
            affected=True,
            explanation="Affected.",
            build_nvr="curl-8.6.0-3.el9",
        )
        data = entry.model_dump()
        assert data["build_nvr"] == "curl-8.6.0-3.el9"
        restored = AffectedPackageEntry(**data)
        assert restored.build_nvr == "curl-8.6.0-3.el9"

    def test_build_nvr_defaults_to_none(self):
        entry = AffectedPackageEntry(
            purl="pkg:rpm/redhat/curl",
            ps_update_stream="rhel-9.6.0.z",
            affected=True,
            explanation="Affected.",
        )
        assert entry.build_nvr is None

    def test_affected_subcomponents_not_in_schema(self):
        assert "affected_subcomponents" not in AffectedPackageEntry.model_fields
        assert "affected_binaries" in AffectedPackageEntry.model_fields


class TestSuggestAffectedPackagesModelPrintableOutcome:
    def test_no_binaries(self):
        model = SuggestAffectedPackagesModel(
            cve_id="CVE-2024-1234",
            affected_packages=[
                AffectedPackageEntry(
                    purl="pkg:rpm/redhat/curl",
                    ps_update_stream="rhel-9.6.0.z",
                    affected=True,
                    explanation="Affected.",
                ),
            ],
            explanation="Overall analysis.",
            data_quality=0.8,
            confidence=0.9,
            disclaimer=DISCLAIMER,
        )
        assert model.printable_outcome() == "1/1 package(s) affected"

    def test_with_binaries(self):
        model = SuggestAffectedPackagesModel(
            cve_id="CVE-2024-1234",
            affected_packages=[
                AffectedPackageEntry(
                    purl="pkg:rpm/redhat/curl",
                    ps_update_stream="rhel-9.6.0.z",
                    affected=True,
                    explanation="Affected.",
                    affected_binaries=[
                        BinaryAffectednessEntry(
                            binary_rpm="libcurl",
                            affected=True,
                            explanation="Yes.",
                        ),
                        BinaryAffectednessEntry(
                            binary_rpm="curl-minimal",
                            affected=False,
                            explanation="No.",
                        ),
                    ],
                ),
                AffectedPackageEntry(
                    purl="pkg:rpm/redhat/glibc",
                    ps_update_stream="rhel-9.6.0.z",
                    affected=False,
                    explanation="Not affected.",
                    affected_binaries=[
                        BinaryAffectednessEntry(
                            binary_rpm="glibc",
                            affected=False,
                            explanation="No.",
                        ),
                    ],
                ),
            ],
            explanation="Overall analysis.",
            data_quality=0.8,
            confidence=0.9,
            disclaimer=DISCLAIMER,
        )
        assert (
            model.printable_outcome() == "1/2 package(s) affected, 3 binaries assessed"
        )
