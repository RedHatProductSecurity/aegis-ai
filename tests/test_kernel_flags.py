async def _canned_exec_feature_with_flags(feature, flaw_data):
    """Fake exec_feature returning a SuggestImpact output with kernel flags."""
    name = feature.__class__.__name__

    if name == "SuggestAffectedComponents":
        return SimpleNamespace(
            components=["kernel"],
            ecosystems=[],
            explanation="test",
            data_quality=0.9,
            confidence=0.9,
            tools_used=[],
        )
    if name == "SuggestDescriptionText":
        return SimpleNamespace(
            suggested_title="Test title",
            suggested_description="Test desc.",
            explanation="test",
            data_quality=0.9,
            confidence=0.9,
            tools_used=[],
        )
    if name == "SuggestCWE":
        return SimpleNamespace(
            cwe=["CWE-416"],
            explanation="test",
            data_quality=0.9,
            confidence=0.9,
            tools_used=[],
        )
    if name == "SuggestImpact":
        return SimpleNamespace(
            impact="IMPORTANT",
            cvss3_score="7.0",
            cvss3_vector="CVSS:3.1/AV:L/AC:H/PR:L/UI:N/S:U/C:N/I:N/A:H",
            explanation="Kernel panic detected",
            data_quality=0.9,
            confidence=0.9,
            tools_used=[],
            _flags=["kpanic"],
        )
    raise ValueError(f"Unknown feature: {name}")


