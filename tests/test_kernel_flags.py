CVE_ID = "CVE-2025-99999"

_DISCLAIMER = (
    "This response was generated by Aegis AI "
    "(https://github.com/RedHatProductSecurity/aegis-ai) "
    "using generative AI for informational purposes. "
    "All findings should be validated by a human expert."
)


def _base_model_kwargs(**overrides):
    """Common kwargs required by AegisFeatureModel base class."""
    defaults = {
        "cve_id": CVE_ID,
        "title": "test",
        "explanation": "test",
        "impact": "LOW",
        "cvss3_score": "3.7",
        "cvss3_vector": "CVSS:3.1/AV:L/AC:L/PR:L/UI:N/S:U/C:N/I:N/A:L",
        "data_quality": 0.9,
        "confidence": 0.9,
        "tools_used": ["osidb_tool"],
        "disclaimer": _DISCLAIMER,
    }
    defaults.update(overrides)
    return defaults


class TestFlagToLabelMapping:
    """Verify the allow-list mapping from classifier features to label names."""

    def test_kernel_panic_maps_to_kpanic(self):
        assert _FLAG_TO_LABEL["kernel_panic"] == "kpanic"

    def test_kernel_panic_plus_uaf_maps_to_kpanic(self):
        assert _FLAG_TO_LABEL["kernel_panic_plus_uaf"] == "kpanic"

    def test_unknown_feature_not_in_mapping(self):
        assert "use_after_free" not in _FLAG_TO_LABEL
        assert "overflow" not in _FLAG_TO_LABEL


class TestSuggestImpactModelFlags:
    """Verify the _flags private attr on SuggestImpactModel."""

    def test_flags_defaults_to_empty_list(self):
        model = SuggestImpactModel(**_base_model_kwargs())
        assert model._flags == []

    def test_flags_not_in_json_schema(self):
        schema = SuggestImpactModel.model_json_schema()
        assert "flags" not in schema.get("properties", {})
        assert "_flags" not in schema.get("properties", {})

    def test_flags_not_in_model_dump(self):
        model = SuggestImpactModel(**_base_model_kwargs())
        model._flags = ["kpanic"]
        dumped = model.model_dump()
        assert "flags" not in dumped
        assert "_flags" not in dumped

    def test_flags_settable_after_construction(self):
        model = SuggestImpactModel(**_base_model_kwargs())
        model._flags = ["kpanic"]
        assert model._flags == ["kpanic"]


