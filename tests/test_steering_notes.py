"""Public-text prompts keep steering notes as internal context."""

import re

import pytest
from pydantic_ai import Agent
from pydantic_ai.messages import ModelRequest, UserPromptPart
from pydantic_ai.models.test import TestModel

from aegis_ai import get_settings
from aegis_ai.features.cve import (
    SuggestDescriptionModel,
    SuggestDescriptionText,
    SuggestImpact,
    SuggestImpactModel,
    SuggestStatementModel,
    SuggestStatementText,
)

CVE_ID = "CVE-2025-1234"


@pytest.mark.asyncio
@pytest.mark.parametrize(
    (
        "feature_type",
        "output_model",
        "output_fields",
        "retained_rule_terms",
        "components",
    ),
    [
        (
            SuggestDescriptionText,
            SuggestDescriptionModel,
            ("title", "description"),
            ("title", "description", "consistent"),
            [],
        ),
        (
            SuggestStatementText,
            SuggestStatementModel,
            ("statement", "mitigation"),
            ("2-4 concise sentences", "< 1000 characters total"),
            [],
        ),
        (
            SuggestImpact,
            SuggestImpactModel,
            ("explanation",),
            ("metric selection guide",),
            ["curl"],
        ),
        (
            SuggestImpact,
            SuggestImpactModel,
            ("explanation",),
            ("kernel-specific tools",),
            ["kernel"],
        ),
    ],
    ids=[
        "title-and-description",
        "statement-and-mitigation",
        "impact",
        "kernel-impact",
    ],
)
async def test_public_text_prompts_keep_steering_notes_internal(
    monkeypatch,
    feature_type,
    output_model,
    output_fields,
    retained_rule_terms,
    components,
):
    monkeypatch.setattr(get_settings(), "safety_enabled", False)
    monkeypatch.setattr(get_settings(), "use_kernel_classifier", False)
    notes = (
        "Private analyst note: inspect the optional frame decoder.\n"
        "Keep the analyst's draft internal."
    )
    output = output_model.model_construct(
        cve_id=CVE_ID,
        data_quality=0.5,
        confidence=0.5,
        disclaimer=(
            "This response was generated by Aegis AI "
            "(https://github.com/RedHatProductSecurity/aegis-ai) using generative AI "
            "for informational purposes. All findings should be validated by a human expert."
        ),
        components=components,
        explanation="Test output",
        impact="MODERATE",
        cvss3_score="5.5",
        cvss3_vector="CVSS:3.1/AV:L/AC:L/PR:L/UI:N/S:U/C:N/I:N/A:H",
        suggested_title="Test title",
        suggested_description="Test description",
        title="Test title",
        description="Test description",
        suggested_statement="Test statement",
        suggested_mitigation="Test mitigation",
    )
    feature = feature_type(
        Agent(model=TestModel(call_tools=[], custom_output_args=output.model_dump()))
    )

    result = await feature.exec(
        CVE_ID, static_context={"steering_notes": notes, "components": components}
    )

    prompts = [
        part.content
        for message in result.all_messages()
        if isinstance(message, ModelRequest)
        for part in message.parts
        if isinstance(part, UserPromptPart)
    ]
    assert len(prompts) == 1, "A valid test-model response should need no retries"
    prompt = prompts[0]
    assert isinstance(prompt, str)
    instructions, separator, context = prompt.partition("\n\nContext:\n")
    assert separator, "The model must receive the CVE context"
    context = context.partition("\n\nFormat:")[0]
    assert f"steering_notes={notes!r}" in context

    # Check the policy in the instructions, not in the supplied notes or schema.
    # Ignore Markdown, line wrapping, and the choice of sentence-range dash.
    rules = [
        " ".join(rule.lower().replace("`", "").replace("–", "-").split())
        for rule in re.split(r"\n\s*-\s+", instructions)
    ]
    policy = next((rule for rule in rules if "steering_notes" in rule), "")
    assert "only as internal guidance" in policy
    assert "do not quote or paraphrase" in policy
    for output_field in output_fields:
        assert output_field in policy

    assert any(all(term in rule for term in retained_rule_terms) for rule in rules), (
        "The existing public-text requirements must still reach the model"
    )
