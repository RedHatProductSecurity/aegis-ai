@pytest.mark.asyncio
async def test_suggest_components_saves_structured_data(
    mock_agent, sample_component_output, monkeypatch
):
    """Test that structured components are saved to aegis_meta."""

    # Mock exec_feature to return our sample output
    async def mock_exec_feature(feature, flaw_data):
        return sample_component_output

    monkeypatch.setattr("aegis_ai.osidb_bot.suggest.exec_feature", mock_exec_feature)

    # Create empty flaw data
    flaw_data = {
        "cve_id": "CVE-2026-88015",
        "uuid": "test-uuid-123",
    }

    # Call suggest_components
    timestamp = datetime.now(timezone.utc)
    changed_fields = await suggest_components(mock_agent, flaw_data, timestamp)

    # Verify changed fields include aegis_meta
    assert "aegis_meta" in changed_fields
    assert "components" in changed_fields

    # Verify component names are saved (backward compatibility)
    assert flaw_data["components"] == ["rclone", "spring-webmvc"]

    # Verify ecosystems are saved
    assert flaw_data.get("_ecosystems") == ["golang", "maven"]

    # Verify structured components are saved to aegis_meta
    assert "aegis_meta" in flaw_data
    assert "structured_components" in flaw_data["aegis_meta"]

    structured = flaw_data["aegis_meta"]["structured_components"]
    assert len(structured) == 2

    # Verify rclone component
    rclone = structured[0]
    assert rclone["name"] == "rclone"
    assert rclone["namespace"] == "github.com/rclone"
    assert rclone["ecosystem"] == "golang"
    assert rclone["purl"] == "pkg:golang/github.com/rclone/rclone"
    assert rclone["first_introduced"] == "0"
    assert rclone["last_affected"] == "1.75.0"
    assert rclone["fixed_in"] == "1.75.1"
    assert "GHSA-p6m2-r3w9-mpxw" in rclone["evidence"]
    assert rclone["confidence"] == 0.95

    # Verify spring-webmvc component
    spring = structured[1]
    assert spring["name"] == "spring-webmvc"
    assert spring["namespace"] == "org.springframework"
    assert spring["ecosystem"] == "maven"
    assert spring["purl"] == "pkg:maven/org.springframework/spring-webmvc"
    assert spring["first_introduced"] == "5.0.0"
    assert spring["last_affected"] == "5.3.20"
    assert spring["fixed_in"] == "5.3.21"
    assert "Spring 5.x" in spring["evidence"]
    assert spring["confidence"] == 0.90


@pytest.mark.asyncio
async def test_suggest_components_handles_null_version_ranges(mock_agent, monkeypatch):
    """Test that components without version ranges are still saved."""

    output = SuggestAffectedComponentsModel(
        cve_id="CVE-2026-6298",
        components=[
            ComponentMatch(
                name="chromium-browser",
                namespace=None,
                ecosystem="generic",
                purl="pkg:generic/chromium-browser",
                first_introduced=None,  # No version data
                last_affected=None,
                fixed_in=None,
                evidence="CVE title mentions Chromium Skia - no version constraints available",
                confidence=0.75,
            ),
        ],
        ecosystems=["generic"],
        explanation="Browser CVE without version data",
        confidence=0.75,
        data_quality=0.70,
        tools_used=[],
        disclaimer="This response was generated by Aegis AI (https://github.com/RedHatProductSecurity/aegis-ai) using generative AI for informational purposes. All findings should be validated by a human expert.",
    )

    async def mock_exec_feature(feature, flaw_data):
        return output

    monkeypatch.setattr("aegis_ai.osidb_bot.suggest.exec_feature", mock_exec_feature)

    flaw_data = {"cve_id": "CVE-2026-6298"}
    timestamp = datetime.now(timezone.utc)
    await suggest_components(mock_agent, flaw_data, timestamp)

    structured = flaw_data["aegis_meta"]["structured_components"]
